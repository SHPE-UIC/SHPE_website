export function getChicagoDateKey(date = new Date()) {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone: 'America/Chicago',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(date)
  const year = parts.find((part) => part.type === 'year').value
  const month = parts.find((part) => part.type === 'month').value
  const day = parts.find((part) => part.type === 'day').value

  return `${year}-${month}-${day}`
}

export function formatEventDate(date) {
  const [year, month, day] = date.split('-').map(Number)
  const dateAtNoonUtc = new Date(Date.UTC(year, month - 1, day, 12))

  return new Intl.DateTimeFormat('en-US', {
    timeZone: 'America/Chicago',
    weekday: 'long',
    month: 'long',
    day: 'numeric',
    year: 'numeric',
  }).format(dateAtNoonUtc)
}

export function getEventGroups(today = getChicagoDateKey()) {
  return {
    today: EVENTS.filter((event) => event.date === today),
    comingUp: EVENTS.filter((event) => event.date > today).sort((a, b) =>
      a.date.localeCompare(b.date)
    ),
    past: EVENTS.filter((event) => event.date < today).sort((a, b) =>
      b.date.localeCompare(a.date)
    ),
  }
}
